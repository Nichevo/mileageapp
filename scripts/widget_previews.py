"""Builds the home-screen widget previews shown in the launcher's widget picker.

For each widget it writes:
  - res/layout/<widget>_preview.xml: the real layout with sample text filled in
    (Android 12+ launchers draw this as the preview);
  - res/drawable-nodpi/<widget>_preview.png: a picture of the same thing, for
    launchers that only use a static image (Samsung One UI often does).

Run from the repo root after changing a widget layout:
    python3 scripts/widget_previews.py
Needs cairosvg (pip install cairosvg). The sample figures are made up.
"""
import os
import re
from xml.sax.saxutils import escape

import cairosvg

RES = 'android/app/src/main/res'
S = 3  # px per dp in the PNGs

BG, TEXT, SUB, ACCENT, ON_ACCENT, BUTTON = '#f2f7f2', '#17251b', '#4a5b4e', '#1f6f3f', '#ffffff', '#dcefe0'
FONT = 'Roboto, DejaVu Sans, sans-serif'

SAMPLE = {
    'widget_fillup': {'widget_title': 'Log a fill-up', 'widget_detail': 'Last 3 Nov · ~420 km left'},
    'widget_trip': {'widget_title': 'Start a trip', 'widget_detail': 'Last trip 24.3 km · Sat'},
    'widget_summary': {
        'widget_title': '2026 so far',
        'widget_detail': '12,480 km · $2,140',
        'widget_economy': '6.9 L/100 km average',
        'widget_next': 'WOF in 12 days',
    },
    'widget_dashboard': {
        'widget_title': '2026 SO FAR',
        'widget_detail': '12,480 km · $2,140',
        'widget_economy': 'Last 3 Nov · 6.8 L/100 km · ~420 km left',
        'widget_next': 'WOF in 12 days',
        'btn_trip_text': 'Start trip',
    },
    'widget_quick': {'btn_trip_text': 'Start trip'},
}


def icon_path(name):
    xml = open(f'{RES}/drawable/{name}.xml').read()
    return ' '.join(re.findall(r'pathData="([^"]+)"', xml))


def preview_layout(widget):
    xml = open(f'{RES}/layout/{widget}.xml').read()
    for vid, text in SAMPLE[widget].items():
        # Set (or replace) the text of the view with this id.
        m = re.search(r'(<TextView[^>]*android:id="@\+id/%s"[^>]*?)(/?>)' % vid, xml, re.S)
        assert m, (widget, vid)
        tag = re.sub(r'\s*android:text="[^"]*"', '', m.group(1))
        tag += '\n            android:text="%s"' % escape(text, {'"': '&quot;'})
        xml = xml[:m.start()] + tag + m.group(2) + xml[m.end():]
    xml = re.sub(r'<!--.*?-->\n?', '', xml, flags=re.S)
    xml = xml.replace('<?xml version="1.0" encoding="utf-8"?>\n',
                      '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/widget_previews.py: sample data for the widget picker. -->\n', 1)
    open(f'{RES}/layout/{widget}_preview.xml', 'w').write(xml)


class Svg:
    def __init__(self, w, h):
        self.w, self.h, self.parts = w, h, []

    def rect(self, x, y, w, h, r, fill):
        self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{fill}"/>')

    def text(self, x, y, s, size, fill, bold=False, anchor='start'):
        self.parts.append(
            f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" fill="{fill}" '
            f'font-weight="{"bold" if bold else "normal"}" text-anchor="{anchor}">{escape(s)}</text>')

    def icon(self, cx, cy, d, name):
        # Accent circle with a 24-unit vector icon inside.
        r = d / 2
        self.parts.append(f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{ACCENT}"/>')
        k = d * 0.6 / 24
        self.parts.append(f'<path transform="translate({cx - 12 * k},{cy - 12 * k}) scale({k})" d="{icon_path(name)}" fill="{ON_ACCENT}"/>')

    def save(self, path):
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w * S}" height="{self.h * S}" viewBox="0 0 {self.w} {self.h}">'
               + ''.join(self.parts) + '</svg>')
        cairosvg.svg2png(bytestring=svg.encode(), write_to=path)


def button(svg, x, y, w, h, icon, label):
    svg.rect(x, y, w, h, 18, BUTTON)
    tw = len(label) * 8.2
    left = x + (w - (30 + 8 + tw)) / 2
    svg.icon(left + 15, y + h / 2, 30, icon)
    svg.text(left + 38, y + h / 2 + 5, label, 14, TEXT, bold=True)


def pngs():
    out = f'{RES}/drawable-nodpi'
    os.makedirs(out, exist_ok=True)

    # 3x1 fill-up and trip: icon, title, detail.
    for widget, icon in [('widget_fillup', 'ic_widget_fuel'), ('widget_trip', 'ic_widget_play')]:
        s = SAMPLE[widget]
        g = Svg(260, 70)
        g.rect(0, 0, 260, 70, 24, BG)
        g.icon(12 + 22, 35, 44, icon)
        g.text(68, 31, s['widget_title'], 15, TEXT, bold=True)
        detail = s['widget_detail']
        g.text(68, 50, detail if len(detail) < 30 else detail[:28] + '…', 13, SUB)
        g.save(f'{out}/{widget}_preview.png')

    # 3x2 summary.
    s = SAMPLE['widget_summary']
    g = Svg(250, 140)
    g.rect(0, 0, 250, 140, 24, BG)
    g.icon(14 + 14, 14 + 14, 28, 'ic_widget_chart')
    g.text(50, 33, s['widget_title'], 15, TEXT, bold=True)
    g.text(14, 72, s['widget_detail'], 18, TEXT)
    g.text(14, 91, s['widget_economy'], 13, SUB)
    g.text(14, 120, s['widget_next'], 13, ACCENT, bold=True)
    g.save(f'{out}/widget_summary_preview.png')

    # 2x2 quick buttons.
    g = Svg(160, 160)
    g.rect(0, 0, 160, 160, 24, BG)
    button(g, 10, 10, 140, 66, 'ic_widget_fuel', 'Fill-up')
    button(g, 10, 84, 140, 66, 'ic_widget_play', SAMPLE['widget_quick']['btn_trip_text'])
    g.save(f'{out}/widget_quick_preview.png')

    # 4x2 dashboard.
    s = SAMPLE['widget_dashboard']
    g = Svg(340, 160)
    g.rect(0, 0, 340, 160, 24, BG)
    g.text(12, 28, s['widget_title'], 12, SUB, bold=True)
    g.text(105, 28, s['widget_detail'], 15, TEXT, bold=True)
    g.text(12, 48, s['widget_economy'], 13, SUB)
    g.text(12, 67, s['widget_next'], 13, ACCENT, bold=True)
    button(g, 12, 96, 154, 52, 'ic_widget_fuel', 'Fill-up')
    button(g, 174, 96, 154, 52, 'ic_widget_play', s['btn_trip_text'])
    g.save(f'{out}/widget_dashboard_preview.png')


def wire_info(widget):
    p = f'{RES}/xml/{widget}_info.xml'
    xml = open(p).read()
    xml = re.sub(r'android:previewLayout="[^"]*"', f'android:previewLayout="@layout/{widget}_preview"', xml)
    if 'android:previewImage' not in xml:
        xml = xml.replace('android:initialLayout=', f'android:previewImage="@drawable/{widget}_preview"\n    android:initialLayout=', 1)
    open(p, 'w').write(xml)


if __name__ == '__main__':
    for w in SAMPLE:
        preview_layout(w)
        wire_info(w)
    pngs()
    print('wrote previews for', ', '.join(SAMPLE))
